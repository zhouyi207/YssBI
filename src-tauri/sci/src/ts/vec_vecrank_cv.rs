/// dim = K − r（协整秩检验维度），返回 [10% / 5% / 1% 显著性] 的右尾临界值
#[inline]
pub fn trace_critical_row(dim: usize, det_order: i32) -> Option<[f64; 3]> {
    if dim < 1 || dim > 12 {
        return None;
    }
    let i = dim - 1;
    Some(match det_order {
        -1 => TRACE_OL_CASE0[i],
        0 => TRACE_OL_CASE1[i],
        1 => TRACE_OL_CASE2[i],
        _ => return None,
    })
}

#[inline]
pub fn max_eigen_critical_row(dim: usize, det_order: i32) -> Option<[f64; 3]> {
    if dim < 1 || dim > 12 {
        return None;
    }
    let i = dim - 1;
    Some(match det_order {
        -1 => MAX_OL_CASE0[i],
        0 => MAX_OL_CASE1[i],
        1 => MAX_OL_CASE2[i],
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ol_trace_case1_dim3_matches_stata_vecrank_manual() {
        let cv = trace_critical_row(3, 0).unwrap();
        assert!((cv[0] - 26.79).abs() < 0.02);
        assert!((cv[1] - 29.68).abs() < 0.02);
        assert!((cv[2] - 35.65).abs() < 0.02);
    }

    #[test]
    fn ol_max_case1_dim3_matches_stata_vecrank_manual() {
        let cv = max_eigen_critical_row(3, 0).unwrap();
        assert!((cv[1] - 20.97).abs() < 0.02);
    }
}
