const fn spec(
    legacy_name: &'static str,
    id: &'static str,
    title: &'static str,
    zh_title: &'static str,
    aliases: &'static [&'static str],
    zh_aliases: &'static [&'static str],
    interface: InterfaceKind,
) -> NodeSpec {
    NodeSpec {
        legacy_name: Some(legacy_name),
        id,
        title,
        zh_title,
        aliases,
        zh_aliases,
        interface,
        kernel: id,
    }
}

const fn builtin_spec(
    id: &'static str,
    title: &'static str,
    zh_title: &'static str,
    aliases: &'static [&'static str],
    zh_aliases: &'static [&'static str],
    interface: InterfaceKind,
) -> NodeSpec {
    NodeSpec {
        legacy_name: None,
        id,
        title,
        zh_title,
        aliases,
        zh_aliases,
        interface,
        kernel: id,
    }
}
