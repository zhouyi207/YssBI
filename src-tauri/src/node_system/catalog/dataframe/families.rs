//! Stable inventory for the DataFrame catalog and its legacy identity subset.

#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum InterfaceKind {
    DataframeSource,
    Limit,
    Rename,
    Project,
    FilterRows,
    Decompose,
    Combine,
    Filter,
    SeriesSelect,
    IntRange,
    SeriesLength,
    SeriesCount,
    SeriesSum,
    SeriesMean,
    NumericCompare,
    StringCompare,
    Standardize,
    InverseStandardize,
    DummyInfo,
    TimeAlign,
    TimeUnary,
    TimeWindow,
    TimeLag,
    PanelAlign,
    PanelDifference,
}

#[derive(Clone, Copy)]
pub(super) struct NodeSpec {
    #[allow(dead_code)]
    pub legacy_name: Option<&'static str>,
    pub id: &'static str,
    pub title: &'static str,
    pub zh_title: &'static str,
    pub aliases: &'static [&'static str],
    pub zh_aliases: &'static [&'static str],
    pub interface: InterfaceKind,
    pub kernel: &'static str,
}

