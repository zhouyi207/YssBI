import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(repositoryRoot, "docs/reference/MODULE_MAP.md");
const outputDirectory = dirname(outputPath);
const checkOnly = process.argv.includes("--check");

function repositoryPath(absolutePath) {
  return relative(repositoryRoot, absolutePath).replaceAll("\\", "/");
}

function outputLink(absolutePath, label) {
  const target = relative(outputDirectory, absolutePath).replaceAll("\\", "/");
  return `[${label}](${target})`;
}

function compareText(left, right) {
  return left.replaceAll("\r\n", "\n") === right.replaceAll("\r\n", "\n");
}

function cargoPackages() {
  const stdout = execFileSync(
    "cargo",
    [
      "metadata",
      "--manifest-path",
      resolve(repositoryRoot, "src-tauri/Cargo.toml"),
      "--no-deps",
      "--format-version",
      "1",
    ],
    { cwd: repositoryRoot, encoding: "utf8" },
  );
  const metadata = JSON.parse(stdout);
  const workspaceMembers = new Set(metadata.workspace_members);
  return metadata.packages
    .filter((entry) => workspaceMembers.has(entry.id))
    .map((entry) => {
      const manifest = resolve(entry.manifest_path);
      const directory = dirname(manifest);
      const readme = resolve(directory, "README.md");
      return {
        name: entry.name,
        directory,
        manifest,
        readme: existsSync(readme) ? readme : null,
      };
    })
    .sort((left, right) => left.name.localeCompare(right.name, "en"));
}

function frontendModules() {
  const modulesRoot = resolve(repositoryRoot, "src/modules");
  return readdirSync(modulesRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => {
      const directory = resolve(modulesRoot, entry.name);
      const publicEntry = resolve(directory, "public.ts");
      return {
        name: entry.name,
        directory,
        publicEntry: existsSync(publicEntry) ? publicEntry : null,
      };
    })
    .sort((left, right) => left.name.localeCompare(right.name, "en"));
}

function renderModuleMap() {
  const lines = [
    "<!-- GENERATED by scripts/generate-module-map.mjs — DO NOT EDIT. -->",
    "",
    "# Module Map",
    "",
    "> Status: Current",
    "> Scope: Cargo workspace packages and frontend module contribution entry points",
    "> Canonical owners: Cargo metadata and repository directories; this file is generated",
    "> Update when: run the generator after workspace or frontend module membership changes",
    "",
    "This is a navigation index, not a responsibility specification. Source-level layer membership and dependency policy are enforced by [Architecture Gates](../development/ARCHITECTURE_GATES.md). Run `pnpm docs:module-map` to regenerate it.",
    "",
    "## Rust workspace packages",
    "",
    "Cargo packages are listed from `cargo metadata`; a README link appears only when that package owns one.",
    "",
    "| Package | Directory | Manifest | Owner README |",
    "| --- | --- | --- | --- |",
  ];

  for (const entry of cargoPackages()) {
    lines.push(
      `| \`${entry.name}\` | \`${repositoryPath(entry.directory)}\` | ${outputLink(entry.manifest, "Cargo.toml")} | ${entry.readme ? outputLink(entry.readme, "README") : "—"} |`,
    );
  }

  lines.push(
    "",
    "## Frontend modules",
    "",
    "Each row is discovered from `src/modules/`. A public entry is shown only when present; consumers still follow the frontend architecture policy rather than importing module internals.",
    "",
    "| Module | Directory | Public entry |",
    "| --- | --- | --- |",
  );

  for (const entry of frontendModules()) {
    lines.push(
      `| \`${entry.name}\` | \`${repositoryPath(entry.directory)}\` | ${entry.publicEntry ? outputLink(entry.publicEntry, "public.ts") : "—"} |`,
    );
  }

  return `${lines.join("\n")}\n`;
}

const generated = renderModuleMap();
if (checkOnly) {
  if (!existsSync(outputPath) || !compareText(readFileSync(outputPath, "utf8"), generated)) {
    process.stderr.write("docs/reference/MODULE_MAP.md is stale; run `pnpm docs:module-map`.\n");
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, generated, "utf8");
}
